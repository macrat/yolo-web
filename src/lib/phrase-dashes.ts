/**
 * ダッシュ（「—」「──」「--」）を前の語に付け、ハイフンで結んだ語（「not-found」「JSON-LD」）をハイフンの後ろで
 * 折らずに組む（DESIGN.md §4）。ブラウザはダッシュの前と「-」の後ろで折るので、そのままではダッシュが行の頭に
 * 来るか、ダッシュだけの行や「-／-」ができ、語が1行に収まる幅でもハイフンで結んだ語が割れる。
 *
 * 前の空白は折れない空白にし、空白の無いダッシュの前と、ダッシュの字どうしのあいだと、語の中のハイフンの後ろには
 * 語結合子（U+2060）を置く。語結合子は見えず、ページ内の検索も元の文で当たる。ハイフンで結んだ語が1行に
 * 収まらないときは、区切りを組む要素の overflow-wrap: anywhere がその語の中で折る。
 *
 * 文字列を受けて文字列を返すだけなので、サーバーでもブラウザでも動く。区切りを組む PhrasedText が使う。
 */

/** ダッシュの前の空白。 */
const SPACE_BEFORE_DASH = /[ \t]+(?=[—―─]|--)/gu;
/**
 * ダッシュの字の前（空白でない字の後ろ）と、ダッシュの字どうしのあいだと、語の中の1つの「-」の後ろ（前後が
 * 空白でも「-」でもなく、後ろが数字でない所。数字の前はブラウザがもともと折らない）。
 */
const INSIDE_OR_BEFORE_DASH =
  /(?<=[^\s])(?=[—―─])|(?<=[—―─])(?=[—―─])|(?<=[^\s-])(?=--)|(?<=-)(?=-)|(?<=[^\s-]-)(?=[^\s\d-])/gu;
const NO_BREAK_SPACE = "\u00A0";
const WORD_JOINER = "\u2060";

/** ダッシュを前の語に付け、ダッシュの中とハイフンで結んだ語の中で折れないようにした文を返す。 */
export function joinDashes(text: string): string {
  return text
    .replace(SPACE_BEFORE_DASH, NO_BREAK_SPACE)
    .replace(INSIDE_OR_BEFORE_DASH, WORD_JOINER);
}
