import { describe, expect, test } from "vitest";
import { toGraphemes, wordStartsOf, wordsOf } from "@/lib/word-starts";

const segmenter = new Intl.Segmenter("ja", { granularity: "word" });

/** 語の辞書が text の中の word を2つ以上の語に刻むか（word の中に辞書の語の境目があるか）。 */
function dictionarySplits(text: string, word: string): boolean {
  const at = text.indexOf(word);
  return [...segmenter.segment(text)].some(
    ({ index }) => index > at && index < at + word.length,
  );
}

describe("wordStartsOf", () => {
  test("語の頭を字の番号で返し、片仮名の続きの中は組み直した語の頭だけを返す", () => {
    expect([...wordStartsOf("メールアドレスバリデーター")]).toEqual([7]);
    expect([...wordStartsOf("フィルタリングパイプライン")]).toEqual([7]);
    expect([...wordStartsOf("リファクタリング")]).toEqual([]);
  });

  test("続きの前からかかる語との境目は残す", () => {
    expect([...wordStartsOf("省エネモード")]).toContain(3);
  });

  test("番号は書記素で数える", () => {
    const text = "👨‍👩‍👧メールアドレスバリデーター";
    expect(toGraphemes(text)[1]).toBe("メ");
    expect([...wordStartsOf(text)]).toContain(8);
  });

  test("辞書の補いの語の中には語の頭を置かず、補いの語のあとの語の頭は残す", () => {
    expect([...wordStartsOf("サイト内検索を")]).toEqual([4, 6]);
    expect([...wordStartsOf("UNIXタイムスタンプ変換")]).toEqual([4, 11]);
    expect([...wordStartsOf("AIマルチエージェント間")]).toEqual([2, 5]);
  });
});

